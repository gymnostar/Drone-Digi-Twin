#!/usr/bin/env python3
"""Write numbers.tex, tab_models.tex and tab_plan.tex for slides.tex from the JSON results.
Missing results become '--' so the deck always compiles."""
import json, time
from pathlib import Path
import numpy as np

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[2]
VAL = ROOT / "DLR/atlas/results/validation.json"
PLAN = ROOT / "DLR/planner/results/plan_summary.json"
val = json.loads(VAL.read_text()) if VAL.exists() else {}
plan = json.loads(PLAN.read_text()) if PLAN.exists() else {}
N = {}


def pct(x, nd=1):
    return "--" if x is None else f"{100 * x:.{nd}f}"


dirs = [d for d in val.get("directions", []) if d % 30 == 0]
N["NDirs"] = str(len(dirs))
conv = val.get("convergence", {})
drifts = [c["drift_last50_over_Uref_probes_ge10m"] for c in conv.values() if "drift_last50_over_Uref_probes_ge10m" in c]
N["MaxDriftPct"] = f"{100 * max(drifts):.2f}" if drifts else "--"
tm = val.get("timing", {})
N["FieldBlendMs"] = f"{1e3 * tm['field_blend_s']:.0f}" if tm else "--"
N["QueryThousandMs"] = f"{1e3 * tm['query_1000pts_prebuilt_s']:.1f}" if tm else "--"
N["SolveMinutes"] = "25--35"
re_ = val.get("reynolds_240", {})
N["ReynoldsRmsTwenty"] = pct(re_.get("20m", {}).get("rmse"))
N["ReynoldsRmsTen"] = pct(re_.get("10m", {}).get("rmse"))

loo = val.get("leave_one_out", {})
b30 = val.get("blend_30deg_255", {})
H = ["10m", "20m", "40m", "60m"]


def mean_over(key):
    if not loo:
        return {h: None for h in H}
    return {h: float(np.mean([loo[t][key][h]["rmse"] for t in loo])) for h in H}


ll, nu, nr, bli, bl = (mean_over(k) for k in ("loglaw_no_buildings", "nearest_unrotated_60deg", "nearest_rotated_60deg",
                                                "blend_linear_60deg", "blend_rotate_60deg"))
if b30:
    N["BlendSentence"] = (f"Rotate, then blend. At the real 30\\,$^\\circ$ spacing (255\\,$^\\circ$ from 240 and 270): "
                          f"{pct(b30['blend_rotate_30deg']['20m']['rmse'])}\\,\\% RMS at 20\\,m, "
                          f"{pct(b30['blend_rotate_30deg']['40m']['rmse'])}\\,\\% at 40\\,m. "
                          f"Plain linear blending: {pct(b30['blend_linear_30deg']['20m']['rmse'])}\\,\\% at 20\\,m.")
elif loo:
    N["BlendSentence"] = (f"Leave-one-out, 60\\,$^\\circ$ gaps ({len(loo)} directions), rotate then blend: "
                          f"{pct(bl['20m'])}\\,\\% RMS at 20\\,m, {pct(bl['40m'])}\\,\\% at 40\\,m. "
                          f"Plain linear blending: {pct(bli['20m'])}\\,\\% and {pct(bli['40m'])}\\,\\%.")
else:
    N["BlendSentence"] = "Leave-one-out results not available yet."

rows = [("Empty-field log-law (no CFD)", "0", ll),
        ("Nearest solved run, as is (60$^\\circ$ gap)", "$\\mu$s", nu),
        ("Nearest solved run, rotated (60$^\\circ$ gap)", "$\\mu$s", nr),
        ("Linear blend of raw vectors (60$^\\circ$ gap)", "$\\mu$s", bli),
        ("\\textbf{Rotate, then blend} (60$^\\circ$ gap)", "$\\mu$s", bl)]
if b30:
    rows.append(("\\textbf{Rotate, then blend} (30$^\\circ$, real spacing)", "$\\mu$s",
                 {h: b30["blend_rotate_30deg"][h]["rmse"] for h in H}))
rows.append(("Full CFD for that direction", "25--35 min", {h: 0.0 for h in H}))
tab = ["\\begin{tabular}{@{}lrrrrr@{}}", "\\toprule",
       "Model & Cost per new direction & 10\\,m & 20\\,m & 40\\,m & 60\\,m \\\\", "\\midrule"]
for name, cost, e in rows:
    tab.append(f"{name} & {cost} & " + " & ".join(f"{pct(e[h])}\\,\\%" if e[h] is not None else "--" for h in H) + " \\\\")
tab += ["\\bottomrule", "\\end{tabular}"]
(HERE / "tab_models.tex").write_text("\n".join(tab) + "\n")

# ---- planner ---------------------------------------------------------------------------------
g = plan.get("graph", {})
N["PlanNodes"] = f"{g.get('nodes', 0):,}".replace(",", "\\,") if g else "--"
N["NPairs"] = str(plan.get("n_pairs", "--"))
maps = sorted((ROOT / "DLR/planner/fig").glob("plan_map_*.png"))
pref = [m for m in maps if m.stem.endswith("_240")] or maps
N["PlanMapFile"] = pref[0].name if pref else "plan_map_240.png"
import plan_table  # noqa: E402  (written after the planner's summary format is known)
tab_plan, tab_levers, sentence = plan_table.build(plan)
(HERE / "tab_plan.tex").write_text(tab_plan)
(HERE / "tab_levers.tex").write_text(tab_levers)
N["PlanSentence"] = sentence

# ---- energy (fixed numbers from DLR/planner/energy.py) -----------------------------------------
import sys
sys.path.insert(0, str(ROOT / "DLR/planner"))
import energy as E  # noqa: E402
vr = E.max_range_speed()
N["HoverW"] = f"{float(E.power_level(0.0)):.1f}"
N["BestJm"] = f"{float(E.power_level(vr)) / vr:.2f}"
N["BestSpeed"] = f"{vr:.1f}"

N["BuildStatus"] = (f"Built {time.strftime('%d %b %Y %H:%M')} from {len(dirs)} solved directions"
                    + (f" (+ validation runs: {', '.join(val.get('extra_runs', []))})" if val.get("extra_runs") else "") + ".")
(HERE / "numbers.tex").write_text("% generated by make_numbers.py\n" +
                                  "".join(f"\\newcommand{{\\{k}}}{{{v}}}\n" for k, v in N.items()))
print("numbers.tex:", ", ".join(f"{k}={v}" for k, v in N.items() if len(v) < 40))
