#!/usr/bin/env python3
"""
Prepares the OpenFOAM case from your STLs:
  * scales STL -> metres, recentres x/y on the terrain centre (UTM-size coordinates break OpenFOAM precision)
  * derives cylinder domain, base-mesh counts, refinement boxes, locationInMesh
  * writes system/caseParams, system/topoSetDict, constant/fvOptions (turbine for ONE wind direction)
Re-run with a different --wind-from to get the disk orientation for another direction.

pip install numpy trimesh
Example:
  python3 make_case.py --buildings buildings.stl --terrain terrain.stl --scale 0.001 \
      --turbine-xy 1234.5 678.9 --rotor-D 82 --hub-height 80 --wind-from 270
(--turbine-xy is in the coordinates of the INPUT STL, after --scale)
"""
import argparse, math, os
import numpy as np, trimesh

ap = argparse.ArgumentParser()
ap.add_argument("--buildings", required=True)
ap.add_argument("--terrain", required=True)
ap.add_argument("--scale", type=float, default=1.0, help="STL unit -> metres (mm: 0.001, cm: 0.01)")
ap.add_argument("--dx0", type=float, default=8.0, help="base (level 0) cell size [m]")
ap.add_argument("--H", type=float, help="reference building height [m] (default: auto, conservative)")
ap.add_argument("--R", type=float, help="domain radius [m] (default: largest circle the terrain covers)")
ap.add_argument("--wind-from", type=float, default=270.0, help="meteorological deg (0=N, 270=from W), x=East y=North")
ap.add_argument("--turbine-xy", type=float, nargs=2, required=True)
ap.add_argument("--rotor-D", type=float, required=True)
ap.add_argument("--hub-height", type=float, required=True, help="hub height above local ground [m]")
ap.add_argument("--levTurb", type=int, default=4, help="refinement level in turbine sphere (match snappyHexMeshDict)")
ap.add_argument("--case", default=".")
A = ap.parse_args()

def load(p):
    m = trimesh.load(p, force="mesh"); m.apply_scale(A.scale); return m

def ground_z(tri, x, y):
    a, b, c = tri[:, 0], tri[:, 1], tri[:, 2]
    d = (b[:,1]-c[:,1])*(a[:,0]-c[:,0]) + (c[:,0]-b[:,0])*(a[:,1]-c[:,1])
    d = np.where(np.abs(d) < 1e-12, np.nan, d)
    l1 = ((b[:,1]-c[:,1])*(x-c[:,0]) + (c[:,0]-b[:,0])*(y-c[:,1]))/d
    l2 = ((c[:,1]-a[:,1])*(x-c[:,0]) + (a[:,0]-c[:,0])*(y-c[:,1]))/d
    l3 = 1 - l1 - l2
    ok = (l1 >= -1e-9) & (l2 >= -1e-9) & (l3 >= -1e-9)
    if not ok.any(): return None
    return float((l1*a[:,2] + l2*b[:,2] + l3*c[:,2])[ok].max())

bld, ter = load(A.buildings), load(A.terrain)
tb = ter.bounds
shift = np.array([(tb[0,0]+tb[1,0])/2, (tb[0,1]+tb[1,1])/2, 0.0])
for m in (bld, ter): m.apply_translation(-shift)
tri_dir = os.path.join(A.case, "constant", "triSurface")
os.makedirs(tri_dir, exist_ok=True)
bld.export(os.path.join(tri_dir, "buildings.stl")); ter.export(os.path.join(tri_dir, "terrain.stl"))
tb, bb = ter.bounds, bld.bounds
tri = ter.triangles

H = A.H or (bb[1,2] - bb[0,2])
zg_min, zg_max = tb[0,2], tb[1,2]
Rmax = 0.98*min(tb[1,0], -tb[0,0], tb[1,1], -tb[0,1])
R = A.R or Rmax
ang = np.linspace(0, 2*np.pi, 73)[:-1]
def covered(r): return all(ground_z(tri, r*math.cos(t), r*math.sin(t)) is not None for t in ang)
if not A.R:
    while R > 10 and not covered(R): R *= 0.97
elif not covered(R):
    print("WARNING: terrain does NOT cover the whole cylinder -> snappyHexMesh will leak under the terrain edge. Extend the terrain or reduce --R.")
rb = float(np.hypot(bld.vertices[:,0], bld.vertices[:,1]).max())
if R < rb + 5*H:
    print(f"WARNING: R={R:.0f} m < buildings radius {rb:.0f} m + 5H ({5*H:.0f} m); lateral boundaries are close to the buildings. Extend the terrain for a bigger domain.")

dx0 = A.dx0
zBot = zg_min - dx0
zTop = max(bb[1,2], zg_max) + 5*H
a_in = 0.5*0.70710678*R; b_out = 0.70710678*R
nI = max(4, math.ceil(2*a_in/dx0)); nR = max(4, math.ceil(0.5*R/dx0)); nz = math.ceil((zTop-zBot)/dx0)
m_ = 20.0
siteMin = (bb[0,0]-m_, bb[0,1]-m_, zg_min-1.0)
siteMax = (bb[1,0]+m_, bb[1,1]+m_, bb[1,2]+1.5*H)

# ---- turbine
tx, ty = A.turbine_xy[0]-shift[0], A.turbine_xy[1]-shift[1]
gz = ground_z(tri, tx, ty)
if gz is None: raise SystemExit("Turbine x/y is outside the terrain STL.")
hub = np.array([tx, ty, gz + A.hub_height])
th = math.radians(A.wind_from)
n_up = np.array([math.sin(th), math.cos(th), 0.0])        # disk normal pointing UPSTREAM (ESI convention)
D = A.rotor_D
thk = 2*dx0/2**A.levTurb
p1, p2 = hub - n_up*thk/2, hub + n_up*thk/2
upstream = hub + n_up*2.5*D
v = lambda x: "(%.4f %.4f %.4f)" % tuple(x)

hdr = lambda cls, obj, loc: f'FoamFile\n{{\n    version 2.0;\n    format ascii;\n    class {cls};\n    location "{loc}";\n    object {obj};\n}}\n\n'
open(os.path.join(A.case, "system", "caseParams"), "w").write(f"""// generated by make_case.py -- shift applied to input coords: {v(shift)}
Rdom    {R:.4f};   mRdom   {-R:.4f};
Ain     {a_in:.4f};  mAin    {-a_in:.4f};
Bout    {b_out:.4f}; mBout   {-b_out:.4f};
zBot    {zBot:.4f};  zTop    {zTop:.4f};
nI      {nI};  nR {nR};  nz {nz};
locationInMesh  ({0.137:.4f} {0.211:.4f} {zTop-0.5*H:.4f});
siteMin  {v(siteMin)};
siteMax  {v(siteMax)};
turbineHub   {v(hub)};
turbineRefR  {0.75*D:.4f};
""")
open(os.path.join(A.case, "system", "topoSetDict"), "w").write(hdr("dictionary","topoSetDict","system") + f"""actions
(
    {{
        name    actuationDisk;
        type    cellSet;
        action  new;
        source  cylinderToCell;
        p1      {v(p1)};
        p2      {v(p2)};
        radius  {D/2:.4f};
    }}
);
""")
open(os.path.join(A.case, "constant", "fvOptions"), "w").write(hdr("dictionary","fvOptions","constant") + f"""turbine1
{{
    type            actuationDiskSource;
    active          yes;
    fields          (U);

    selectionMode   cellSet;
    cellSet         actuationDisk;

    variant         Froude;
    diskDir         {v(n_up)};      // normal, pointing UPSTREAM (wind from {A.wind_from:.0f} deg)
    diskArea        {math.pi*D*D/4:.3f};       // pi*D^2/4
    // PLACEHOLDERS -- replace with your turbine's curves (Function1, function of wind speed at the monitor point)
    Cp              0.45;               // e.g. table ((4 0.30) (8 0.46) (12 0.40))
    Ct              0.80;               // e.g. table ((4 0.90) (8 0.80) (12 0.45))

    // upstream sampling of the undisturbed wind (~2.5 D upstream of the hub)
    monitorMethod   points;
    monitorCoeffs   {{ points ( {v(upstream)} ); }}
    // older ESI releases (<~v2112): use   upstreamPoint {v(upstream)};   instead of monitorMethod/monitorCoeffs
}}
""")
cells = (nI*nI + 4*nI*nR)*nz
print(f"""
shift subtracted from input coordinates : {v(shift)}   <-- apply the SAME shift to the Sionna scene
domain: R={R:.1f} m, z={zBot:.1f} .. {zTop:.1f} m, H_ref={H:.1f} m (check this!)
base mesh: {nI}x{nI} core + 4 rings {nI}x{nR}, nz={nz}  -> ~{cells:,} base cells (before refinement)
turbine hub (local) {v(hub)}, ground {gz:.1f} m, diskDir {v(n_up)}
""")
